test('removing an unfinished NBME Test retains answers and archives both saved copies across reload', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-10-17T16:00:00Z'))
  await network(page)
  await page.goto(url)
  await page.getByRole('group', { name: 'Mode', exact: true }).getByRole('button', { name: 'Test', exact: true }).click()
  await page.getByRole('button', { name: 'Start 5-question block', exact: true }).click()
  await page.getByText('Synthetic saved option C', { exact: true }).click()
  await page.getByRole('button', { name: 'Submit answer', exact: true }).click()
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  await expect(page.getByText('Finish your Test block to update the daily goal.')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Ask Claude for a session' })).toBeVisible()
  const before = await page.evaluate(() => window.__leerNbmeReal())
  const id = Object.values(before.sessions).find(s => s.mode === 'test')!.id
  expect(Object.values(before.attempts).filter(a => a.sessionId === id)).toHaveLength(1)
  await page.getByText('Saved blocks', { exact: true }).click()
  await page.getByRole('button', { name: 'Remove 5-item Test block', exact: true }).click()
  await page.getByRole('dialog', { name: 'Remove saved block?' }).getByRole('button', { name: 'Remove block', exact: true }).click()
  await expect(page.getByText('No saved blocks.')).toBeVisible()
  const after = await page.evaluate(() => ({ nbme: window.__leerNbmeReal(), study: JSON.parse(localStorage.getItem('qa-myqbank-state')!) }))
  expect(after.nbme.attempts).toEqual(before.attempts)
  expect(after.nbme.sessions[id].completedAt).toBeDefined()
  expect(after.nbme.archivedSessions?.[id]).toBeDefined()
  expect(after.study.myqbankBlocks[id].completedAt).toBeDefined()
  expect(after.study.myqbankBlocks[id].archivedAt).toBeDefined()
  // Simulate a device receiving the block tombstone before its NBME copy catches up.
  await page.evaluate(stale => {
    const key = Object.keys(localStorage).find(k => k.startsWith('step1-backup:nbme-state:'))!
    const backup = JSON.parse(localStorage.getItem(key)!)
    localStorage.setItem(key, JSON.stringify({ ...backup, state: stale, savedAt: Date.now() + 60000 }))
  }, before)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Build a block' })).toBeVisible()
  await page.getByText('Saved blocks', { exact: true }).click()
  await expect(page.getByText('No saved blocks.')).toBeVisible()
  await expect(page.getByText('Finish your Test block to update the daily goal.')).toHaveCount(0)
  const restored = await page.evaluate(() => window.__leerNbmeReal())
  expect(restored.attempts).toEqual(before.attempts)
  await expect.poll(async () => page.evaluate(id => !!window.__leerNbmeReal().archivedSessions?.[id], id)).toBe(true)
  await expect.poll(async () => page.evaluate(id => window.__leerNbmeReal().sessions[id].completedAt, id)).toBeDefined()
})
