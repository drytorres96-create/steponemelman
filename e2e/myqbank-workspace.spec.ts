test('selecting highlighted text erases it; keyboard selection waits until Shift is released', async ({page}) => {
  await network(page);await page.goto(url);await page.getByRole('button',{name:'Start 5-question block'}).click()
  const text=page.locator('.mq-stem .mq-highlight-text').first()
  const select=()=>text.evaluate(el=>{const range=document.createRange();range.selectNodeContents(el);const s=getSelection()!;s.removeAllRanges();s.addRange(range)})
  await select();await text.dispatchEvent('pointerup');await expect(text.locator('mark')).toHaveCount(1)
  await select();await text.dispatchEvent('pointerup');await expect(text.locator('mark')).toHaveCount(0)
  await select();await text.dispatchEvent('keyup',{key:'ArrowRight',shiftKey:true});await expect(text.locator('mark')).toHaveCount(0)
  await text.dispatchEvent('keyup',{key:'Shift'});await expect(text.locator('mark')).toHaveCount(1)
  await page.getByRole('button',{name:'Labs',exact:true}).press('Enter')
  await expect(page.getByLabel('Lab reference',{exact:true})).toBeVisible()
})

